const { summarize, dateKey, mockEvents } = require('../analytics');

test('UTC+7 dates, unique users/sessions, date filtering and monthly grouping', () => {
  const time = Date.parse('2026-11-09T18:00:00Z');
  assert.equal(dateKey(time), '2026-11-10');
  const event = { timestamp: time, visitor:'one', session:'session-one', path:'/', referrer:'Trực tiếp', device:'Desktop', browser:'Chrome' };
  const result = summarize([event, { ...event, path:'/#studio' }, { ...event, timestamp:time-86400000, visitor:'other' }], '2026-11-10', '2026-11-10');
  assert.deepEqual(result.totals, { visits:1, users:1, pageviews:2 });
  assert.equal(summarize([event], '2026-10-01','2026-11-10','month').series.length, 2);
  assert.equal(mockEvents(time).some(e => e.timestamp > time), false);
  const demo = summarize(mockEvents(time), '2026-10-12', '2026-11-10');
  assert.equal(dateKey(demo.recent[0].timestamp), '2026-11-10');
  assert.ok(demo.totals.visits >= demo.totals.users);
});

